#!/usr/bin/env python3
"""Rebuild font_tc.h, Momowo's 12 px Traditional Chinese font (Fusion Pixel, SIL OFL).

Characters: the common Traditional set (Big5 level 1, as used in Taiwan and Hong Kong), the
common Simplified set (GB2312 level 1) converted to Traditional with OpenCC in its general, Taiwan
and Hong Kong forms (e.g. 爲 and 為), plus every Traditional Chinese label in lang.h, plus CJK punctuation and the letters of romanised
Pali. That covers screen labels, AI replies and most headlines while keeping the font small enough
for the ESP32-C3.

Needs: Python 3, `pip install opencc-python-reimplemented`, u8g2's bdfconv
(github.com/olikraus/u8g2, tools/font/bdfconv: run `make` there), and the Fusion Pixel 12px
proportional BDF (github.com/TakWolf/fusion-pixel-font releases, file fusion-pixel-12px-proportional-zh_hant.bdf).

Usage: python3 make_font_tc.py path/to/bdfconv path/to/fusion-pixel-12px-proportional-zh_hant.bdf
Run it from the sketch folder (next to lang.h); it writes font_tc.h there.
"""
import os, re, subprocess, sys, tempfile

import opencc

bdfconv, bdf = sys.argv[1], sys.argv[2]
chars = set()

# Big5 level 1 (0xA440-0xC67E): the 5401 most common Traditional characters
for hi in range(0xA4, 0xC7):
    for lo in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
        if (hi << 8 | lo) > 0xC67E:
            break
        try:
            chars.add(bytes([hi, lo]).decode("big5"))
        except UnicodeDecodeError:
            pass

# GB2312 level 1 (rows 0xB0-0xD7): the 3755 most common hanzi, as Traditional
simp = []
for hi in range(0xB0, 0xD8):
    for lo in range(0xA1, 0xFF):
        try:
            simp.append(bytes([hi, lo]).decode("gb2312"))
        except UnicodeDecodeError:
            pass
for cfg in ("s2t", "s2tw", "s2hk"):            # e.g. 为 -> 爲 (s2t) but 為 (Taiwan, Hong Kong)
    chars.update(opencc.OpenCC(cfg).convert("".join(simp)))
chars.update(simp)                              # many characters are the same in both

# Every Traditional Chinese string in lang.h (third column of each row)
here = os.path.dirname(os.path.abspath(__file__))
lang = open(os.path.join(here, "..", "lang.h"), encoding="utf-8").read()
for row in re.findall(r"^\s*\{(\".*)\},\s*//", lang, re.M):
    cols = re.findall(r'"((?:[^"\\]|\\.)*)"', row)
    if len(cols) >= 3:
        chars.update(cols[2])
for extra in re.findall(r"//\s*TC-EXTRA:(.*)$", lang, re.M):   # extra characters listed in lang.h
    chars.update(extra.strip())

chars.update("，。、！？；：「」『』（）《》〈〉…—─·．～％＋－＝／°℃　“”‘’｜【】")
chars.update(chr(c) for c in range(0x20, 0x7F))
chars.update(chr(c) for c in range(0xA0, 0x100))   # Latin-1: accented names in headlines
chars.update("ĀāĪīŪūṂṃṄṅṬṭḌḍṆṇḶḷ")              # romanised Pali, for the Dhammapada quotes

with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".txt", delete=False) as f:
    f.write("".join(sorted(chars)))
    utf8 = f.name
out = os.path.join(here, "..", "font_tc.h")
subprocess.run([bdfconv, "-f", "1", "-b", "0", "-u", utf8, "-n", "u8g2_font_fusion12_tc", "-o", out, bdf], check=True)
os.unlink(utf8)
src = open(out, encoding="utf-8").read()
header = ("// Fusion Pixel 12px (zh_hant), SIL Open Font License 1.1: github.com/TakWolf/fusion-pixel-font\n"
          "// Generated by tools/make_font_tc.py; about %d characters.\n#pragma once\n" % len(chars))
src = src.replace('const uint8_t u8g2_font_fusion12_tc', 'static const uint8_t u8g2_font_fusion12_tc')
open(out, "w", encoding="utf-8").write(header + src)
print("wrote", out, len(chars), "characters")
